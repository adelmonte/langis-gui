#!/usr/bin/env python3
"""Builds langis-gui's translations from Signal Desktop's (AGPL, as the icons).

Run from the repo with Desktop's source next to it:
    python3 scripts/i18n.py ../Signal-Desktop
It reads every string the code shows (see `t(...)` and `tf("icu:...")`
in src/), finds the Desktop message each is, and writes, for each language
the app offers, assets/i18n/<locale>.json: {"plain": {english: text},
"icu": {key: message}}. It also writes src/i18n_locales.rs.
"""
import glob, json, os, re, sys

DESKTOP = sys.argv[1] if len(sys.argv) > 1 else '../Signal-Desktop'
# Languages egui can draw: no right-to-left or complex-shaping scripts.
OFFERED = ['en', 'af-ZA', 'az-AZ', 'bg-BG', 'bs-BA', 'ca', 'cs', 'da', 'de', 'el', 'es', 'et-EE', 'eu', 'fi', 'fr',
           'ga-IE', 'gl-ES', 'hr-HR', 'hu', 'id', 'it', 'ja', 'ka-GE', 'kk-KZ', 'ko', 'ky-KG', 'lt-LT', 'lv-LV',
           'mk-MK', 'ms', 'nb', 'nl', 'pl', 'pt-BR', 'pt-PT', 'ro-RO', 'ru', 'sk-SK', 'sl-SI', 'sq-AL', 'sr', 'sv',
           'sw', 'tl-PH', 'tr', 'uk-UA', 'vi', 'yue', 'zh-CN', 'zh-HK', 'zh-Hant']


def load(locale):
    path = os.path.join(DESKTOP, '_locales', locale, 'messages.json')
    return {k: v['messageformat'] for k, v in json.load(open(path)).items() if k.startswith('icu:') and 'messageformat' in v}


def norm(s):
    return s.replace('\u2019', "'").replace('\u201c', '"').replace('\u201d', '"').replace('\u2026', '...').strip()


def rust_unescape(s):
    s = re.sub(r'\\u\{([0-9a-fA-F]+)\}', lambda m: chr(int(m.group(1), 16)), s)
    return s.replace('\\"', '"').replace('\\n', '\n').replace('\\\\', '\\')


def icu_plain(mf):
    """A message with no arguments, as text (ICU's '' is a quote)."""
    if '{' in mf or '<' in mf:
        return None
    return mf.replace("''", "'")


en = load('en')
# Desktop can have several messages with the same English; each language
# gets the translation most of them have.
by_english, all_keys = {}, {}
for k, v in en.items():
    p = icu_plain(v)
    if p is not None:
        by_english.setdefault(norm(p), k)
        all_keys.setdefault(norm(p), []).append(k)

# What the code asks for.
plain_used, icu_used = {}, set()
for f in glob.glob('src/*.rs'):
    text = open(f).read()
    # Every literal that's a Desktop message: wrapped where shown, or kept
    # in a constant and translated where it's drawn (`tr(label)`).
    for m in re.finditer(r'"((?:[^"\\]|\\.)*)"', text):
        lit = m.group(1)
        key = by_english.get(norm(rust_unescape(lit)))
        if key:
            plain_used[rust_unescape(lit)] = key
    for m in re.finditer(r'"(icu:[A-Za-z0-9_.\-]+)"', text):
        icu_used.add(m.group(1))

names = json.load(open(os.path.join(DESKTOP, 'build/locale-display-names.json')))
os.makedirs('assets/i18n', exist_ok=True)
rows = []
for loc in OFFERED:
    msgs = en if loc == 'en' else load(loc)
    plain = {}
    for english, key in plain_used.items():
        if loc == 'en':
            continue
        votes = {}
        for k in all_keys.get(norm(english), [key]):
            t = msgs.get(k)
            p = icu_plain(t) if t else None
            if p:
                votes[p] = votes.get(p, 0) + 1
        if votes:
            # Most common; one that differs from English wins a tie.
            plain[english] = max(votes.items(), key=lambda kv: (kv[1], kv[0] != english))[0]
    icu = {k: msgs[k] for k in sorted(icu_used) if k in msgs}
    # Every offered language's name in this one (Desktop's
    # locale-display-names), for the language list.
    shown = {o: names.get(loc, {}).get(o, o) for o in OFFERED}
    with open(f'assets/i18n/{loc}.json', 'w') as out:
        json.dump({'plain': plain, 'icu': icu, 'names': shown}, out, ensure_ascii=False, sort_keys=True, separators=(',', ':'))
    native = names.get(loc, {}).get(loc, loc)
    english_name = names.get('en', {}).get(loc, loc)
    rows.append(f'    ("{loc}", "{native}", "{english_name}", include_str!("../assets/i18n/{loc}.json")),')

with open('src/i18n_locales.rs', 'w') as out:
    out.write('// Generated by scripts/i18n.py from Signal Desktop\'s translations; do not edit.\n\n')
    out.write('/// (locale, its name in itself, its name in English, its messages).\n')
    out.write('pub const LOCALES: &[(&str, &str, &str, &str)] = &[\n' + '\n'.join(rows) + '\n];\n')
print(f'{len(plain_used)} plain strings, {len(icu_used)} ICU messages, {len(OFFERED)} languages')
